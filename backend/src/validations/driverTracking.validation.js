import { z } from 'zod';
import { LOCATION_BATCH } from '../constants/driverTracking.js';

/**
 * Dart `DateTime.toUtc().toIso8601String()` emits microseconds
 * (`...00.123456Z`) which Zod's datetime regex rejects. Accept epoch ms,
 * epoch seconds, and any string `Date` can parse, then store ms.
 */
const isoDate = z.preprocess((value) => {
  if (typeof value === 'number' && Number.isFinite(value)) {
    return value > 0 && value < 1e12 ? Math.round(value * 1000) : Math.round(value);
  }
  if (typeof value === 'string' && value.trim()) {
    const asNum = Number(value);
    if (Number.isFinite(asNum) && asNum > 0) {
      return asNum < 1e12 ? Math.round(asNum * 1000) : Math.round(asNum);
    }
    const ms = new Date(value).getTime();
    if (Number.isFinite(ms)) return ms;
  }
  return value;
}, z.number().int().positive());

export const issueTrackingTokenSchema = z.object({
  /**
   * Stable per-install id generated by the wrapper and persisted in
   * SharedPreferences. Scopes revocation to one phone — without it a driver
   * cannot sign a lost device out without signing every device out.
   */
  deviceId: z.string().trim().min(8, 'deviceId must be at least 8 characters').max(128),
  platform: z.enum(['android', 'ios', 'web']).optional().default('android'),
  appVersion: z.string().trim().max(32).optional().default(''),
});

export const revokeTrackingTokenSchema = z.object({
  deviceId: z.string().trim().min(8).max(128).optional(),
  /** Sign out every device — used on logout, not on go-offline. */
  allDevices: z.boolean().optional().default(false),
});

const optionalNum = z.preprocess(
  (v) => (v === '' || v === undefined ? undefined : v),
  z.coerce.number().finite().optional().nullable(),
);

const fixSchema = z.object({
  lat: z.coerce.number().min(-90).max(90),
  lng: z.coerce.number().min(-180).max(180),
  accuracy: z.coerce.number().nonnegative().optional().nullable(),
  heading: optionalNum,
  speed: optionalNum,
  /** When the OS produced the fix — not when it was uploaded. */
  capturedAt: isoDate,
});

const batchBodySchema = z.object({
  fixes: z
    .array(fixSchema)
    .min(1, 'fixes must contain at least one entry')
    .max(
      LOCATION_BATCH.MAX_FIXES,
      `fixes may contain at most ${LOCATION_BATCH.MAX_FIXES} entries per request`,
    ),
});

/**
 * Single-fix body, kept for compatibility with the shape `main` was posting
 * before the two location implementations were merged. `capturedAt` is
 * optional here because that caller never sent one — it is filled in with
 * receipt time, which is the best available answer for a payload that did not
 * record when the fix was taken.
 */
const singleFixBodySchema = z.object({
  lat: z.coerce.number().gte(-90).lte(90),
  lng: z.coerce.number().gte(-180).lte(180),
  accuracy: z.coerce.number().nonnegative().optional().nullable(),
  heading: optionalNum,
  speed: optionalNum,
  capturedAt: isoDate.optional(),
});

/**
 * Accepts either shape and always yields `{ fixes: [...] }`, so the ingest
 * service has exactly one input to reason about.
 */
export const locationBatchSchema = z
  .union([batchBodySchema, singleFixBodySchema])
  .transform((body) =>
    'fixes' in body
      ? body
      : { fixes: [{ ...body, capturedAt: body.capturedAt ?? Date.now() }] },
  );
